//===================================================
//関数名:build_fault_cone
//機能:故障範囲特定(故障箇所から到達できる信号線を求め、故障回路の変数番号を割り当てる)
//戻り値：int 正常終了:SUCCESS(=0) , 異常終了:ERROR(=-1)
//引数：故障箇所の信号線，目標故障の番号(0: 一次故障)
//===================================================
int build_fault_cone(NLIST* site, int idx) {
	int i;
	NLIST* nlist;

	fc_ppo = 0;//PPO数初期化

	//-----------------------------------------------
	//	故障回路の添え字初期化			   
	//-----------------------------------------------
	for (i = 0; i < n_net; i++) {
		nl[i].suf_fc = nl[i].suf_2t; //2時刻目の添え字で初期化
	}
	//-----------------------------------------------				
	//	故障回路のFAULT_PASS初期化
	//-----------------------------------------------
	for (i = 0; i < n_net; i++) { 
		nl[i].fault_pass = NO;
	}

	//-----------------------------------------------
	//	故障伝搬変数の初期化(一次故障のみ使用)
	//-----------------------------------------------
	if (idx == 0) {
		for (i = 0; i < n_net; i++) {
			nl[i].prop = 0;
		}
	}

	//---------------------------------------------------------------------
	//故障範囲の特定
	//---------------------------------------------------------------------
	//-----------------------------------------------
	//故障範囲特定
	//-----------------------------------------------
	site->fault_pass = YES;
	enqueue(site);
	//-----------------------------------------------
	//故障信号線から到達可能な信号線の探索
	//-----------------------------------------------
	while (queue_emp() != 0) {
		nlist = dequeue();		//デキュー

		nlist->fault_pass = YES;//故障到達可能な信号線に設定
		nlist->suf_fc = bool_id;	//故障回路のブール変数IDを設定
		bool_id++;           	//ブール変数IDを更新
		if (idx == 0 && opt.fault_propagation) { // [FP INTEGRATION]
			nlist->prop = bool_id;
			bool_id++;
		}
		if (nlist->ppo_flag != 1) {//回路の最後の信号線ではないか判断していると思う
			for (i = 0; i < nlist->n_out; i++) {//複数の出力なら、それぞれエンキュー
				if (nlist->out[i]->fault_pass == NO) {
					nlist->out[i]->fault_pass = YES;
					enqueue(nlist->out[i]);
				}
			}
		}
	}

	//故障回路に含まれるPPO数算出
	for (i = 0; i < n_net; i++) {
		if (nl[i].fault_pass == YES && nl[i].ppo_flag == 1) fc_ppo++;
	}

	return SUCCESS;
}
