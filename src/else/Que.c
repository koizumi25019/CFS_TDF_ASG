//------------------------------------------------------------------------
//  信号線のキュー(循環キュー)。故障範囲の探索(fault_cone.c)で使う
//------------------------------------------------------------------------
#include <stdio.h>
#include <stdlib.h>

#include "../header/Define.h"

//=========================================================================
//  関数名 : enqueue
//  機  能 : キューに信号線を入れる。あふれたら異常終了する(容量は信号線数+1で足りる)
//=========================================================================
void enqueue(NLIST *data) {
	Que.que[Que.rear] = data;
	Que.num += 1;
	Que.rear += 1;
	if (Que.max == Que.rear) {
		Que.rear = 0;
	}
	if (Que.max < Que.num) {
		printf("[ERROR] Queue overflow (capacity %d).\n", Que.max);
		exit(EXIT_FAILURE);
	}
}

//=========================================================================
//  関数名 : dequeue
//  機  能 : キューの先頭から信号線を1つ取り出す
//=========================================================================
NLIST* dequeue(void) {
	NLIST *p = Que.que[Que.front];

	Que.que[Que.front] = NULL;
	Que.num -= 1;
	Que.front += 1;
	if (Que.max == Que.front) {
		Que.front = 0;
	}
	return p;
}

//=========================================================================
//  関数名 : queue_emp
//  機  能 : キューに信号線が残っているか
//  戻り値 : 1(残っている), 0(空)
//=========================================================================
int queue_emp(void) {
	return Que.num != 0;
}
